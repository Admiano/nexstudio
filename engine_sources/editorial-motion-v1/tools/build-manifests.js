#!/usr/bin/env node
/**
 * Bundle the editorial data files into one synchronous browser script, and
 * write the package manifest that records what the system actually ships.
 * The runtime modules read their data at load time, so the browser needs it
 * assigned to globals before any runtime script runs.
 */
const fs = require('fs');
const path = require('path');

const root = path.join(__dirname, '..');
const read = (p) => JSON.parse(fs.readFileSync(path.join(root, p), 'utf8'));

const data = {
  NEX_EDITORIAL_LEXICON: read('manifests/editorial-lexicon.json'),
  NEX_EDITORIAL_RULES: read('manifests/editorial-rules.json'),
  NEX_PEEPS_SEMANTICS: read('manifests/peeps-semantics.json'),
  NEX_PEEPS_PARTS: read('assets/peeps/parts-index.json')
};

const bundle = ['/* Generated by tools/build-manifests.js — do not edit. */']
  .concat(Object.entries(data).map(([key, value]) => `window.${key} = ${JSON.stringify(value)};`))
  .join('\n') + '\n';
fs.writeFileSync(path.join(root, 'manifests/editorial-data.js'), bundle);

const { registries } = require('./load-registries.js');
const reg = registries();
const parts = data.NEX_PEEPS_PARTS.parts;

const manifest = {
  id: 'nex.editorial-motion',
  version: require(path.join(root, 'package.json')).version,
  ratios: ['16:9', '1:1', '9:16'],
  source: {
    foundation: 'NexMind paper-motion (vendored)',
    cast: data.NEX_PEEPS_PARTS.source
  },
  counts: {
    typography: reg.typography.length,
    icons: reg.icons.length,
    mediaContainers: reg.media.length,
    motion: reg.motion.length,
    peepsParts: Object.values(parts).reduce((n, group) => n + group.length, 0),
    peepsGroups: Object.fromEntries(Object.entries(parts).map(([k, v]) => [k, v.length])),
    peepsCompositions: Object.keys(data.NEX_PEEPS_PARTS.compositions)
  },
  entrypoints: {
    browser: 'runtime/editorial.js',
    node: 'runtime/editorial-director.js',
    data: 'manifests/editorial-data.js',
    explorer: 'compositions/editorial-explorer.html'
  },
  generated: new Date().toISOString().slice(0, 10)
};
fs.writeFileSync(path.join(root, 'manifests/editorial-manifest.json'), JSON.stringify(manifest, null, 2) + '\n');

console.log('manifests/editorial-data.js', (bundle.length / 1024).toFixed(1) + ' kB');
console.log('manifests/editorial-manifest.json', JSON.stringify(manifest.counts));
