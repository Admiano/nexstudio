#!/usr/bin/env python3
"""Hard characterization guard: Sketch may only use validated Whiteboard cast.

These tests deliberately DO NOT certify a character bridge. They demonstrate
that the former home-made SVG actor cannot be generated by the director or
rendered from a directly supplied plan. Native Whiteboard integration remains
a distinct release blocker.
"""
from pathlib import Path
import sys
import unittest

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "tools"))

from scene_director import direct_film, plan_film, _mature_sketch_action


def source_beat(person=False):
    subject = {
        "id": "speaker",
        "kind": "object",
        "glyph": "TILE",
        "phrase": "courier" if person else "pump",
        "label": "courier" if person else "pump",
        "size": "hero",
        "params": {"visual_class": "person" if person else "machine"},
    }
    return {
        "beat_id": "b01",
        "narration": "A courier waits." if person else "A pump starts.",
        "display_units": [{"text": "A courier waits." if person else "A pump starts.",
                           "role": "hero", "anchor_word": "A", "emphasis": .9}],
        "illustration": {"form": "OBJECT_STAGE", "entities": [subject],
                         "relations": [], "program": []},
    }


class UnauthorizedSketchCharacterRegression(unittest.TestCase):
    def test_director_refuses_unapproved_procedural_person(self):
        with self.assertRaisesRegex(
            RuntimeError, "SCENEBAM_WHITEBOARD_CHARACTER_INTEGRATION_REQUIRED"
        ):
            direct_film("sketch", [source_beat(person=True)])

    def test_nonhuman_native_illustrations_remain_authorable(self):
        beat = source_beat(person=False)
        report = direct_film("sketch", [beat])
        self.assertEqual(report["style"], "sketch")
        self.assertEqual(report["scenes"][0]["actor_actions"], [])
        self.assertEqual(report["sketch_visual_coverage_failures"], [])

    def test_native_acting_outweighs_reductive_step_widget(self):
        # General source graph test: no one-off topic branch or extra character.
        narration = "First the pump sends water to the tank, then the tank feeds a house."
        beat = {
            "beat_id": "b01", "narration": narration,
            "illustration": {
                "form": "PROCESS_PIPELINE",
                "entities": [
                    {"id": "pump", "kind": "object", "glyph": "PUMP",
                     "asset_ref": "icon.local.pump", "phrase": "pump"},
                    {"id": "tank", "kind": "object", "glyph": "TANK",
                     "asset_ref": "icon.local.tank", "phrase": "tank"},
                ],
                "relations": [
                    {"type": "flows_to", "source": "pump", "target": "tank"},
                ],
                "program": [
                    {"op": "DRAW", "target": "pump", "at": {"word": "pump"},
                     "duration_ms": 280},
                    {"op": "CONNECT", "target": "pump->tank",
                     "at": {"word": "sends"}, "duration_ms": 480},
                ],
            },
        }
        self.assertTrue(_mature_sketch_action(beat))
        self.assertNotEqual(plan_film("sketch", [beat])[0].family,
                            "spoken_process")
        # Without the complete original illustrated action graph, the native
        # scene repertoire remains available rather than being disabled.
        stripped = dict(beat, illustration={
            **beat["illustration"], "relations": [], "program": []
        })
        self.assertFalse(_mature_sketch_action(stripped))
        self.assertEqual(plan_film("sketch", [stripped])[0].family,
                         "spoken_process")

    def test_no_old_actor_binding_from_director(self):
        source = (ROOT / "tools" / "scene_director.py").read_text()
        self.assertNotIn("bind_actor_performances(beat)", source)

    def test_direct_browser_render_entry_also_refuses_synthetic_person(self):
        runtime = (ROOT / "runtime" / "editorial-runtime.js").read_text()
        self.assertIn("SCENEBAM_WHITEBOARD_CHARACTER_INTEGRATION_REQUIRED", runtime)
        self.assertIn("plan.director_style === 'sketch' && (il.entities || []).some", runtime)


if __name__ == "__main__":
    unittest.main()
